"""保持字体完整字节，以只读片段复用另一份内置字体。 / Preserve complete font bytes through read-only spans shared with another builtin font."""
import argparse
import hashlib
import json
import pathlib
import struct


def glyphs(data):
    """验证SFNT边界并返回原始glyf片段，不修改字形或映射。 / Validate SFNT bounds and return original glyf spans without changing outlines or maps."""
    if len(data) < 12 or data[:4] != b'\x00\x01\x00\x00':
        raise ValueError('Expected a TrueType SFNT')
    count = struct.unpack_from('>H', data, 4)[0]
    if 12+count*16 > len(data):
        raise ValueError('Truncated table directory')
    tables = {}
    for at in range(12, 12+count*16, 16):
        tag = bytes(data[at:at+4])
        offset, size = struct.unpack_from('>II', data, at+8)
        if tag in tables or offset > len(data) or size > len(data)-offset:
            raise ValueError('Invalid table span')
        tables[tag] = (offset, size)
    if any(tag not in tables for tag in (b'head', b'maxp', b'loca', b'glyf')):
        raise ValueError('Missing TrueType tables')
    if tables[b'head'][1] < 54 or tables[b'maxp'][1] < 6:
        raise ValueError('Truncated font header')
    count = struct.unpack_from('>H', data, tables[b'maxp'][0]+4)[0]
    mode = struct.unpack_from('>h', data, tables[b'head'][0]+50)[0]
    if mode not in (0, 1) or tables[b'loca'][1] < (count+1)*(4 if mode else 2):
        raise ValueError('Invalid loca table')
    offsets = [struct.unpack_from('>I' if mode else '>H', data, tables[b'loca'][0]+i*(4 if mode else 2))[0]*(1 if mode else 2) for i in range(count+1)]
    if offsets[0] != 0 or any(a > b for a, b in zip(offsets, offsets[1:])) or offsets[-1] > tables[b'glyf'][1]:
        raise ValueError('Invalid glyph bounds')
    start = tables[b'glyf'][0]
    return start, [(start+a, start+b) for a, b in zip(offsets, offsets[1:])]


def share(data, base):
    """逐字节匹配后合并相邻片段，构建后完整还原验SHA。 / Match exact bytes, merge adjacent spans, then verify the fully reconstructed SHA."""
    if not data or len(data) >= 1 << 31 or len(base) >= 1 << 31:
        raise ValueError('Font view exceeds offset encoding')
    _, base_glyphs = glyphs(base)
    lookup = {}
    for a, b in base_glyphs:
        if a != b:
            lookup.setdefault(base[a:b], a)
    start, chunks = glyphs(data)
    local, spans = bytearray(), []
    def append(raw, reference=None):
        if not raw:
            return
        offset = (reference | 0x80000000) if reference is not None else len(local)
        if reference is None:
            local.extend(raw)
        end = (spans[-1][0] if spans else 0)+len(raw)
        begin = spans[-2][0] if len(spans) > 1 else 0
        if spans and spans[-1][1]+spans[-1][0]-begin == offset and (spans[-1][1] >> 31) == (offset >> 31):
            spans[-1] = (end, spans[-1][1])
        else:
            spans.append((end, offset))
    append(data[:start])
    for a, b in chunks:
        append(data[a:b], lookup.get(data[a:b]))
    append(data[chunks[-1][1] if chunks else start:])
    restored, begin = bytearray(), 0
    for end, offset in spans:
        bank = base if offset & 0x80000000 else local
        offset &= 0x7fffffff
        restored.extend(bank[offset:offset+end-begin])
        begin = end
    if bytes(restored) != data or hashlib.sha256(restored).digest() != hashlib.sha256(data).digest():
        raise ValueError('Font reconstruction mismatch')
    return bytes(local), spans


def generate(source, base_path, output, report=None):
    """仅生成构建目录内的视图数据；原字体及许可保持。 / Generate view data only in the build directory; retain original fonts and licenses."""
    data, base = source.read_bytes(), base_path.read_bytes()
    local, spans = share(data, base)
    rows = ['/* 由tools/embed_font_view.py生成，禁止手改。 / Generated by tools/embed_font_view.py; do not edit. */', '#include "pn_font_blob.h"',
            'extern const uint8_t pn_reading_font_bytes[];', 'static const uint8_t local_bytes[]={']
    rows.extend(','.join(map(str, local[i:i+32]))+',' for i in range(0, len(local), 32))
    rows.extend(['};', 'static const pn_font_span_t spans[]={'])
    rows.extend('{'+str(end)+'u,'+str(offset)+'u},' for end, offset in spans)
    rows.extend(['};', 'const pn_font_blob_t pn_ui_font_blob={local_bytes,pn_reading_font_bytes,'+str(len(local))+'u,'+str(len(base))+'u,spans,'+str(len(spans))+'u,'+str(len(data))+'u};',
                 'const size_t pn_ui_font_size='+str(len(data))+'u;',
                 'const uint8_t pn_ui_font_sha256[32]={'+','.join(map(str, hashlib.sha256(data).digest()))+'};', ''])
    output.write_text('\n'.join(rows), encoding='utf-8')
    info = {'original_bytes': len(data), 'local_bytes': len(local), 'spans': len(spans), 'directory_bytes': len(spans)*8,
            'storage_saving_before_reader_code': len(data)-len(local)-len(spans)*8, 'exact': True,
            'source_sha256': hashlib.sha256(data).hexdigest(), 'shared_sha256': hashlib.sha256(base).hexdigest()}
    if report:
        report.write_text(json.dumps(info, indent=2)+'\n', encoding='utf-8')
    print(json.dumps(info))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=pathlib.Path)
    parser.add_argument('base', type=pathlib.Path)
    parser.add_argument('output', type=pathlib.Path)
    parser.add_argument('--report', type=pathlib.Path)
    args = parser.parse_args()
    generate(args.source, args.base, args.output, args.report)
